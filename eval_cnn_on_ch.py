"""
Zero-shot evaluation of a trained surrogate (from initial_Cnn.py) on
Cahn-Hilliard structures generated by generate_cahn_hilliard.py.

NO training happens here: the saved model + its normalizer are loaded and
applied to every CH sample (no train/val/test split -- all CH samples are test).

Usage:
  python eval_cnn_on_ch.py \
      --run-dir runs/2026-10-19_14-02-11_scalar_n20000 \
      --data-glob "cahn_hilliard_test/res_64/**/result2D_*.nc"

Writes into <run-dir>/ch_eval[_<tag>]/:
    ch_metrics.json        CH metrics + in-distribution metrics from run.json
    ch_predictions.csv     per sample: file, vf, true, pred, abs error
    ch_parity.png          parity plots kxx / kxy / kyy (CH vs y=x)
    ch_error_vs_vf.png     |error| vs volume fraction
"""

import argparse
import csv
import glob
import json
import os

import numpy as np
import torch

import initial_Cnn as cnn          # reuse the EXACT loader + model class


def metrics(true, pred):
    out = {}
    for i, n in enumerate(cnn.LABEL_NAMES):
        t, p = true[:, i], pred[:, i]
        err = p - t
        ss_tot = np.sum((t - t.mean()) ** 2)
        out[n] = {
            "MAE": float(np.mean(np.abs(err))),
            "RMSE": float(np.sqrt(np.mean(err ** 2))),
            # R2 is meaningless when labels barely vary (kxy) -> None
            "R2": float(1 - np.sum(err ** 2) / ss_tot) if t.std() > 1e-3 else None,
            "true_range": [float(t.min()), float(t.max())],
        }
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run-dir", required=True,
                    help="training run folder containing surrogate_model.pt and run.json")
    ap.add_argument("--data-glob", required=True)
    ap.add_argument("--kappa-attr", default=None,
                    help="override; default = KAPPA_ATTR used in training (from run.json)")
    ap.add_argument("--tag", default=None)
    args = ap.parse_args()

    # ---- training config: use the same label attribute as in training ----
    run_json = os.path.join(args.run_dir, "run.json")
    train_info = json.load(open(run_json)) if os.path.exists(run_json) else {}
    cfg = train_info.get("config", {})
    cnn.KAPPA_ATTR = args.kappa_attr or cfg.get("KAPPA_ATTR", cnn.KAPPA_ATTR)
    cnn.DROP_NONCONVERGED = True
    train_shape = train_info.get("dataset", {}).get("density_shape")

    out_dir = os.path.join(args.run_dir, "ch_eval" + (f"_{args.tag}" if args.tag else ""))
    os.makedirs(out_dir, exist_ok=True)

    # ---- data (same preprocessing as training) ----
    files = sorted(glob.glob(args.data_glob, recursive=True))
    X, Y, _, data_info = cnn.load_dataset(args.data_glob)
    if train_shape and list(X.shape[1:]) != list(train_shape):
        print(f"!! WARNING: CH grid {list(X.shape[1:])} != training grid {train_shape}")
    vf = X.reshape(len(X), -1).mean(1)
    greyness = ((X > 0.1) & (X < 0.9)).reshape(len(X), -1).mean(1)
    print(f"CH inputs: vf {vf.min():.2f}-{vf.max():.2f}, mean greyness {greyness.mean():.3f}")
    if cnn.KAPPA_ATTR == "kappa_eff" and greyness.mean() < 0.01:
        print("  note: model was trained on GREY rho (kappa_eff) but CH inputs are binary "
              "-> extra distribution shift on top of the morphology change")

    # ---- model + normalizer from checkpoint ----
    ckpt = torch.load(os.path.join(args.run_dir, "surrogate_model.pt"),
                      map_location=cnn.DEVICE)
    model = cnn.MicrostructureCNN().to(cnn.DEVICE)
    model.load_state_dict(ckpt["state_dict"])
    model.eval()                                     # BatchNorm uses running stats
    y_mean = ckpt["y_mean"].to(cnn.DEVICE)
    y_std = ckpt["y_std"].to(cnn.DEVICE)
    print(f"normalizer={ckpt.get('normalizer')}  mean={y_mean.cpu().numpy()}  "
          f"std={y_std.cpu().numpy()}")

    preds = []
    with torch.no_grad():
        for i in range(0, len(X), 64):
            xb = torch.from_numpy(X[i:i + 64]).to(cnn.DEVICE)
            preds.append((model(xb) * y_std + y_mean).cpu().numpy())
    P = np.concatenate(preds)

    # ---- metrics: all CH, and only CH inside the training label range ----
    m_all = metrics(Y, P)
    lab = train_info.get("dataset", {}).get("label_stats", {})
    in_range = np.ones(len(Y), bool)
    for i, n in [(0, "kxx"), (2, "kyy")]:
        if n in lab:
            in_range &= (Y[:, i] >= lab[n]["min"]) & (Y[:, i] <= lab[n]["max"])
    m_in = metrics(Y[in_range], P[in_range]) if in_range.sum() > 2 else None
    m_train = train_info.get("test_metrics")

    print(f"\n{'':6s}{'in-dist test (TO)':>24s}{'CH all':>24s}{'CH in-range':>24s}")
    print(f"{'':6s}{'RMSE / R2':>24s}{'RMSE / R2':>24s}{'RMSE / R2':>24s}")
    fmt = lambda d: ("-" if d is None else
                     f"{d['RMSE']:.4f} / " + ("n/a" if d.get('R2') is None else f"{d['R2']:.3f}"))
    for n in cnn.LABEL_NAMES:
        print(f"{n:6s}{fmt(m_train.get(n) if m_train else None):>24s}"
              f"{fmt(m_all[n]):>24s}{fmt(m_in[n] if m_in else None):>24s}")
    print(f"CH samples: {len(Y)} total, {int(in_range.sum())} inside training kxx/kyy range")

    # ---- save ----
    with open(os.path.join(out_dir, "ch_metrics.json"), "w") as f:
        json.dump({"kappa_attr": cnn.KAPPA_ATTR, "data_glob": args.data_glob,
                   "n_samples": int(len(Y)), "n_in_range": int(in_range.sum()),
                   "ch_all": m_all, "ch_in_range": m_in,
                   "in_distribution_test": m_train,
                   "data_info": data_info}, f, indent=2)

    with open(os.path.join(out_dir, "ch_predictions.csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["file", "vf", "in_train_range"]
                   + [f"true_{n}" for n in cnn.LABEL_NAMES]
                   + [f"pred_{n}" for n in cnn.LABEL_NAMES]
                   + [f"abserr_{n}" for n in cnn.LABEL_NAMES])
        # load_dataset may skip files -> only label rows when counts match
        names = files if len(files) == len(Y) else [f"idx_{k}" for k in range(len(Y))]
        for k in range(len(Y)):
            w.writerow([names[k], f"{vf[k]:.4f}", int(in_range[k])]
                       + [f"{v:.6g}" for v in Y[k]] + [f"{v:.6g}" for v in P[k]]
                       + [f"{v:.6g}" for v in np.abs(P[k] - Y[k])])

    # ---- plots ----
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, axs = plt.subplots(1, 3, figsize=(13, 4.3))
    for i, (ax, n) in enumerate(zip(axs, cnn.LABEL_NAMES)):
        ax.scatter(Y[in_range, i], P[in_range, i], s=10, label="CH in train range")
        ax.scatter(Y[~in_range, i], P[~in_range, i], s=10, marker="x",
                   label="CH outside range")
        lo = min(Y[:, i].min(), P[:, i].min()); hi = max(Y[:, i].max(), P[:, i].max())
        ax.plot([lo, hi], [lo, hi], "k--", lw=1)
        r2 = m_all[n]["R2"]
        ax.set_title(f"{n}: RMSE={m_all[n]['RMSE']:.4f}"
                     + ("" if r2 is None else f"  R²={r2:.3f}"))
        ax.set_xlabel(f"true {n} (muSpectre)"); ax.set_ylabel(f"predicted {n} (CNN)")
    axs[0].legend(fontsize=8)
    fig.tight_layout(); fig.savefig(os.path.join(out_dir, "ch_parity.png"), dpi=150)

    fig, ax = plt.subplots(figsize=(6, 4.3))
    for i, n in [(0, "kxx"), (2, "kyy")]:
        ax.scatter(vf, np.abs(P[:, i] - Y[:, i]), s=10, label=n)
    ax.set_xlabel("volume fraction"); ax.set_ylabel("|pred - true|")
    ax.set_title("CH error vs volume fraction"); ax.legend()
    fig.tight_layout(); fig.savefig(os.path.join(out_dir, "ch_error_vs_vf.png"), dpi=150)

    print(f"\nsaved -> {out_dir}")


if __name__ == "__main__":
    main()
